const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  fs.mkdirSync('.checks', { recursive: true });
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: '.checks/desktop.png', fullPage: true });
    assert(await page.evaluate(() => document.body.scrollWidth <= innerWidth));
    console.log('PASS: desktop lobby, local fonts, responsive bounds');
    await page.getByRole('button', { name: 'QUICK PLAY', exact: true }).click();
    await page.getByRole('button', { name: 'ENGAGE', exact: true }).waitFor({ timeout: 30000 });
    await page.screenshot({ path: '.checks/battle-ready.png' });
    await page.getByRole('button', { name: 'ENGAGE', exact: true }).click();
    await page.waitForTimeout(250);
    await page.keyboard.down('KeyF');
    await page.waitForFunction(() => Number(document.querySelector('.hud-score>b')?.textContent) >= 100, null, { timeout: 10000 });
    await page.keyboard.up('KeyF');
    console.log('Gameplay HUD:', await page.locator('.hud-score').innerText(), 'ammo', await page.locator('.ammo-count').innerText());
    await page.screenshot({ path: '.checks/battle.png' });
    assert(Number(await page.locator('.hud-score>b').innerText()) >= 100, 'First target must be playable within seconds');
    await page.keyboard.press('KeyP');
    await page.getByRole('heading', { name: 'TAKE A BREATHER.' }).waitFor();
    await page.getByRole('button', { name: 'End operation & save score', exact: true }).click();
    await page.getByRole('heading', { name: 'OPERATOR DOWN.' }).waitFor();
    await page.screenshot({ path: '.checks/game-over.png' });
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('squadstrike-scores')));
    assert(saved.length === 1 && saved[0].score >= 100);
    console.log('PASS: firing, elimination, pause, game-over, saved high score');
    await page.getByRole('button', { name: 'ONE MORE ROUND', exact: true }).click();
    await page.waitForTimeout(300);
    assert.equal(await page.locator('.hud-score>b').innerText(), '0000');
    await page.keyboard.press('KeyP');
    await page.getByRole('button', { name: 'Return to lobby', exact: true }).click();
    await page.getByRole('button', { name: 'CREATE ROOM', exact: true }).click();
    await page.getByLabel('ROOM NAME', { exact: true }).fill('Browser Test Squad');
    await page.getByLabel('VISIBILITY', { exact: true }).selectOption('true');
    await page.getByRole('button', { name: 'Dust Basin', exact: true }).click();
    await page.locator('form').getByRole('button', { name: 'CREATE ROOM', exact: true }).click();
    await page.getByRole('heading', { name: 'BROWSER TEST SQUAD' }).waitFor();
    await page.screenshot({ path: '.checks/room.png' });
    console.log('Room UI:', await page.locator('.invite-code').innerText());
    await page.getByRole('button', { name: 'Leave room', exact: true }).click();
    await page.getByRole('button', { name: 'Leaderboard', exact: true }).click();
    assert.equal(await page.locator('.score-table tbody tr').count(), 1);
    console.log('PASS: instant restart, room creation, local leaderboard');
    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
    const mp = await mobile.newPage();
    mp.on('pageerror', e => errors.push('mobile: ' + e.message));
    await mp.goto('http://localhost:3000', { waitUntil: 'networkidle' });
    await mp.evaluate(() => document.fonts.ready);
    await mp.screenshot({ path: '.checks/mobile.png', fullPage: true });
    assert(await mp.evaluate(() => document.body.scrollWidth <= innerWidth));
    await mp.getByRole('button', { name: 'QUICK PLAY', exact: true }).tap();
    await mp.getByRole('button', { name: 'ENGAGE', exact: true }).waitFor({ timeout: 30000 });
    await mp.getByRole('button', { name: 'ENGAGE', exact: true }).tap();
    const fire = await mp.locator('.touch-fire').boundingBox();
    const cdp = await mobile.newCDPSession(mp);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: fire.x + fire.width / 2, y: fire.y + fire.height / 2, id: 1 }] });
    await mp.waitForFunction(() => Number(document.querySelector('.hud-score>b')?.textContent) >= 100, null, { timeout: 10000 });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    console.log('Mobile gameplay:', await mp.locator('.hud-score').innerText());
    assert(await mp.locator('.touch-joystick').isVisible());
    assert(Number(await mp.locator('.hud-score>b').innerText()) >= 100);
    await mp.screenshot({ path: '.checks/mobile-battle.png' });
    await mp.getByRole('button', { name: 'Pause game', exact: true }).tap();
    await mp.getByRole('heading', { name: 'TAKE A BREATHER.' }).waitFor();
    console.log('PASS: mobile layout, touch firing, touch pause');
    console.log('Browser errors:', JSON.stringify(errors));
    assert.equal(errors.length, 0, 'Browser should run without console errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
